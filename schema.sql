create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  role text not null default 'user' check (role in ('admin','user')),
  created_at timestamptz not null default now()
);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'display_name',
      case lower(split_part(new.email,'@',1))
        when 'user2' then 'User 2'
        when 'user3' then 'User 3'
        else split_part(new.email,'@',1)
      end),
    case lower(split_part(new.email,'@',1))
      when 'otabek' then 'admin'
      else 'user'
    end
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

create table if not exists public.assets (
  id bigint generated by default as identity primary key,
  name text not null,
  inventory_number text not null unique,
  serial_number text,
  room text,
  responsible text,
  acceptance_date date,
  status text not null default 'В наличии',
  comments text,
  photo_path text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists(select 1 from public.profiles p where p.id = (select auth.uid()) and p.role = 'admin');
$$;

alter table public.profiles enable row level security;
alter table public.assets enable row level security;

drop policy if exists "profile self or admin read" on public.profiles;
create policy "profile self or admin read" on public.profiles
for select to authenticated using (id = (select auth.uid()) or public.is_admin());

drop policy if exists "assets read authenticated" on public.assets;
create policy "assets read authenticated" on public.assets
for select to authenticated using (true);

drop policy if exists "assets insert authenticated" on public.assets;
create policy "assets insert authenticated" on public.assets
for insert to authenticated with check (true);

drop policy if exists "assets update authenticated" on public.assets;
create policy "assets update authenticated" on public.assets
for update to authenticated using (true) with check (true);

drop policy if exists "assets delete admin only" on public.assets;
create policy "assets delete admin only" on public.assets
for delete to authenticated using (public.is_admin());

-- Private bucket for photos. Access only to signed-in users.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('asset-photos','asset-photos',false,8388608,array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public=false, file_size_limit=8388608,
allowed_mime_types=array['image/jpeg','image/png','image/webp'];

drop policy if exists "asset photos authenticated read" on storage.objects;
create policy "asset photos authenticated read" on storage.objects
for select to authenticated using (bucket_id='asset-photos');

drop policy if exists "asset photos authenticated upload" on storage.objects;
create policy "asset photos authenticated upload" on storage.objects
for insert to authenticated with check (bucket_id='asset-photos');

drop policy if exists "asset photos authenticated update" on storage.objects;
create policy "asset photos authenticated update" on storage.objects
for update to authenticated using (bucket_id='asset-photos') with check (bucket_id='asset-photos');

drop policy if exists "asset photos admin delete" on storage.objects;
create policy "asset photos admin delete" on storage.objects
for delete to authenticated using (bucket_id='asset-photos' and public.is_admin());

